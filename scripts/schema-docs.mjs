#!/usr/bin/env node
// Generates docs/schema-reference.md from schemas/*.schema.json so the field reference never drifts.
// Usage: node scripts/schema-docs.mjs [--check]   (--check exits 1 when the committed file is stale)
import fs from 'node:fs';
import { schemaPath, TYPES } from '../lib/validate.mjs';

const OUT = new URL('../docs/schema-reference.md', import.meta.url);
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

function typeOf(s) {
  if (s.enum) return s.enum.map((v) => `\`${v}\``).join(', ');
  if (s.type === 'array') return s.items?.type === 'object' ? 'list of objects' : `list of ${s.items?.type || 'any'}`;
  return s.type || 'any';
}

function rules(s) {
  return [
    s.pattern && `pattern \`${s.pattern}\``,
    s.minLength != null && `min ${s.minLength} chars`,
    s.maxLength != null && `max ${s.maxLength} chars`,
    s.minItems != null && `at least ${s.minItems}`,
    s.minimum != null && `>= ${s.minimum}`,
  ].filter(Boolean).join(', ');
}

// One table per object: the root, then every nested object or list of objects.
function tables(s, path, out) {
  const props = Object.entries(s.properties || {});
  out.push(`| Field | Type | Required | Rules | Description |`, `|---|---|---|---|---|`);
  for (const [k, p] of props) {
    out.push(`| \`${k}\` | ${cell(typeOf(p))} | ${(s.required || []).includes(k) ? 'yes' : ''} | ${cell(rules(p))} | ${cell(p.description)} |`);
  }
  for (const [k, p] of props) {
    const inner = p.type === 'object' && p.properties ? p : p.type === 'array' && p.items?.type === 'object' ? p.items : null;
    if (!inner) continue;
    out.push('', `#### \`${path}.${k}${p.type === 'array' ? '[]' : ''}\``, '');
    if (p.description) out.push(cell(p.description), '');
    tables(inner, `${path}.${k}${p.type === 'array' ? '[]' : ''}`, out);
  }
}

export function render() {
  const out = ['# Schema reference', '', '<!-- Generated by scripts/schema-docs.mjs from schemas/*.schema.json. Do not edit by hand; run `npm run docs`. -->', '',
    'Every candidate is a JSON object. Fields not listed here are rejected. Semantic rules beyond these tables are listed in the [guide](guide.md#diagnostics).', ''];
  out.push(...TYPES.map((t) => `- [\`${t}\`](#${t})`), '');
  const examples = fs.readdirSync(new URL('../examples/', import.meta.url)).sort();
  for (const t of TYPES) {
    const s = JSON.parse(fs.readFileSync(schemaPath(t), 'utf8'));
    const ex = examples.find((f) => f.endsWith(`.${t}.json`));
    out.push(`## ${t}`, '', `${s.description}${ex ? ` Example: [\`${ex}\`](../examples/${ex}).` : ''}`, '', '### Root', '');
    tables(s, '$', out);
    out.push('');
  }
  return out.join('\n');
}

const text = render();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== text) { console.error('docs/schema-reference.md is stale; run npm run docs'); process.exit(1); }
} else {
  fs.mkdirSync(new URL('../docs/', import.meta.url), { recursive: true });
  fs.writeFileSync(OUT, text);
  console.log('wrote docs/schema-reference.md');
}
